require 'spec_helper'
require_relative '../lib/sssd_spec_helpers'

describe 'sssd::domain' do
  context 'supported operating systems' do
    on_supported_os.each do |os, os_facts|
      context "on #{os}" do
        let(:facts) { os_facts }

        let(:title) { 'ldap' }
        let(:params) do
          {
            id_provider: 'ldap',
          }
        end

        it { is_expected.to compile.with_all_deps }
        it { expect(entry_content("puppet_domain_#{title}")).not_to match(%r{=\s*$}) }

        it 'edits each setting in place' do
          is_expected.to contain_ini_setting("sssd /etc/sssd/conf.d/50_puppet_domain_#{title}.conf [domain/#{title}] id_provider")
            .with_value('ldap')
            .with_key_val_separator(' = ')
            .that_requires('Package[sssd]')
            .that_notifies('Class[sssd::service]')
        end

        it 'leaves unset settings alone' do
          is_expected.not_to contain_ini_setting("sssd /etc/sssd/conf.d/50_puppet_domain_#{title}.conf [domain/#{title}] description")
        end

        context 'with custom_options' do
          let(:params) do
            super().merge(
              custom_options: {
                # Deliberately out of alphabetical order: the entries are
                # sorted by key before they are rendered.
                'dyndns_update' => 'true',
                'ad_site' => 'Default-First-Site-Name',
              },
            )
          end

          it { is_expected.to compile.with_all_deps }

          # On sssd::domain, custom_options are ADDITIVE: they do not replace
          # the options generated by the other parameters the way the
          # sssd::service::* classes do.
          it {
            expect(entry_content("puppet_domain_#{title}")).to match(%r{^id_provider = ldap$})
          }

          # Sorted by key and added after the parameter-driven settings.
          it {
            expect(entry_content("puppet_domain_#{title}")).to match(%r{^id_provider = ldap$.*^ad_site = Default-First-Site-Name\ndyndns_update = true$}m)
          }
        end

        context 'with custom_options removing a setting' do
          let(:params) { super().merge(custom_options: { 'ad_site' => 'absent' }) }

          it {
            is_expected.to contain_ini_setting("sssd /etc/sssd/conf.d/50_puppet_domain_#{title}.conf [domain/#{title}] ad_site")
              .with_ensure('absent')
          }
        end

        context 'with custom_options overriding a parameter' do
          let(:params) { super().merge(custom_options: { 'id_provider' => 'proxy' }) }

          it { is_expected.to compile.with_all_deps }
          it { expect(entry_content("puppet_domain_#{title}")).to match(%r{^id_provider = proxy$}) }
        end

        context 'with simple access provider parameters' do
          let(:params) do
            super().merge(
              access_provider: 'simple',
              simple_allow_groups: ['linux-admins', 'linux-users'],
              simple_deny_users: ['baduser'],
              # Explicitly empty: the option must be omitted, never rendered
              # with an empty value.
              simple_allow_users: [],
            )
          end

          it { is_expected.to compile.with_all_deps }

          # Arrays render as the comma-separated lists sssd-simple(5) expects.
          it {
            expect(entry_content("puppet_domain_#{title}")).to match(%r{^simple_allow_groups = linux-admins,linux-users$})
          }

          it {
            expect(entry_content("puppet_domain_#{title}")).to match(%r{^simple_deny_users = baduser$})
          }

          it {
            expect(entry_content("puppet_domain_#{title}")).not_to include('simple_allow_users')
          }

          context 'with a list set to absent' do
            let(:params) { super().merge(simple_allow_groups: 'absent') }

            it {
              is_expected.to contain_ini_setting("sssd /etc/sssd/conf.d/50_puppet_domain_#{title}.conf [domain/#{title}] simple_allow_groups")
                .with_ensure('absent')
            }
          end

          it {
            expect(entry_content("puppet_domain_#{title}")).not_to include('simple_deny_groups')
          }

          # Rendered in sssd-simple(5) order (deny_users before allow_groups),
          # after the other parameter-driven lines.
          it {
            expect(entry_content("puppet_domain_#{title}")).to match(%r{^access_provider = simple$.*^simple_deny_users = baduser\nsimple_allow_groups = linux-admins,linux-users$}m)
          }

          context 'combined with custom_options' do
            let(:params) do
              super().merge(
                custom_options: { 'ad_site' => 'Default-First-Site-Name' },
              )
            end

            it { is_expected.to compile.with_all_deps }

            # The parameter-driven simple_* settings come first; custom_options
            # stay at the very end.
            it {
              expect(entry_content("puppet_domain_#{title}")).to match(%r{^simple_allow_groups = linux-admins,linux-users$.*^ad_site = Default-First-Site-Name$}m)
            }
          end

          # The two failures Sssd::IniListItem exists to prevent.  Both are
          # rejected at compile time because sssd.conf offers no way to quote
          # or escape either character.
          context 'with a name containing a comma' do
            # 'Contractors, External' is a legal LDAP/AD CN.  Rendered, sssd
            # would read it as two groups, neither of which exists, and the
            # deny rule would silently never fire -- access control failing
            # open, which is worse than failing to compile.
            let(:params) { super().merge(simple_deny_groups: ['Contractors, External']) }

            it { is_expected.to compile.and_raise_error(%r{parameter 'simple_deny_groups'}) }
          end

          context 'with a name containing a newline' do
            # Would inject an arbitrary extra line into the [domain/...]
            # section.
            let(:params) { super().merge(simple_allow_users: ["alice\ndebug_level = 9"]) }

            it { is_expected.to compile.and_raise_error(%r{parameter 'simple_allow_users'}) }
          end
        end
      end
    end
  end
end
